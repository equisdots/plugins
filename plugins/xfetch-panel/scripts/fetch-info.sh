#!/usr/bin/env bash
# xfetch-panel — system fetch producer: one "key|value" line per field.
set -uo pipefail
os="$(. /etc/os-release 2>/dev/null; printf '%s' "${PRETTY_NAME:-Linux}")"
kern="$(uname -r)"
user="$(whoami 2>/dev/null)"
host="$(hostname 2>/dev/null)"
up="$(uptime -p 2>/dev/null | sed 's/^up //')"
sh="$(basename "${SHELL:-zsh}")"
wm="${XDG_CURRENT_DESKTOP:-Hyprland}"
cpu="$(awk -F: '/model name/{gsub(/^ +/,"",$2);print $2;exit}' /proc/cpuinfo 2>/dev/null)"
[ -n "$cpu" ] || cpu="$(uname -m)"
mem="$(free -h 2>/dev/null | awk '/Mem:/{print $3" / "$2}')"
disk="$(df -h / 2>/dev/null | awk 'NR==2{print $3" / "$2}')"
printf 'user|%s@%s\n' "$user" "$host"
printf 'os|%s\n' "$os"
printf 'kernel|%s\n' "$kern"
printf 'arch|%s\n' "$(uname -m)"
printf 'uptime|%s\n' "$up"
printf 'shell|%s\n' "$sh"
printf 'wm|%s\n' "$wm"
printf 'cpu|%s\n' "$cpu"
printf 'memory|%s\n' "$mem"
printf 'disk|%s\n' "$disk"
